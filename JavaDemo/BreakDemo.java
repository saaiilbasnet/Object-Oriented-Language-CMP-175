/*
 * Problem: Demonstrate `break` by stopping a for-loop once i reaches 3.
 */
public class BreakDemo {
    public static void main(String[] args) {
        for (int i = 0; i < 5; i++) {
            if (i == 3) {
                break;
            }
            System.out.println("Saaiil");
        }
    }
}
