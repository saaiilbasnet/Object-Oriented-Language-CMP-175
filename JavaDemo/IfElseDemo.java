/*
 * Problem: Check whether a number is even or odd using if-else.
 */
public class IfElseDemo {
    public static void main(String[] args) {
        int num = 10;

        if (num % 2 == 0) {
            System.out.println("Even");
        } else {
            System.out.println("Odd");
        }
    }
}
